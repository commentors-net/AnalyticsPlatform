@pytest.mark.asyncio
async def test_sparse_traffic_trends_rendering(client: AsyncClient, askanna_setup):
    """Verify sparse Traffic Trends provides contiguous day/hour buckets without data gaps (Task 6)."""
    app_id = askanna_setup["app_id"]
    write_key = askanna_setup["write_key"]
    auth_headers = askanna_setup["auth_headers"]

    now = datetime.now(timezone.utc)
    start_date = now - timedelta(days=5)

    # Ingest 1 event on day 2
    payload = {
        "batch": [
            {
                "event_id": str(uuid.uuid4()),
                "event_type": "pageview",
                "event_name": "pageview",
                "page_path": "/",
                "visitor_id": None,
                "session_id": None,
                "timestamp": (start_date + timedelta(days=2)).isoformat(),
            }
        ]
    }
    r = await client.post("/v1/events/batch", json=payload, headers={"X-Write-Key": write_key})
    assert r.status_code == 202

    # Query timeseries for the 5-day window
    ts_resp = await client.get(
        f"/api/v1/analytics/timeseries?app_id={app_id}&environment=live&interval=day&start_date={start_date.strftime('%Y-%m-%dT%H:%M:%SZ')}&end_date={now.strftime('%Y-%m-%dT%H:%M:%SZ')}",
        headers=auth_headers,
    )
    assert ts_resp.status_code == 200
    points = ts_resp.json()
    # Contiguous days: should have at least 6 points (day 0 through day 5)
    assert len(points) >= 6
    # Day 2 has 1 pageview, other days have 0
    total_pv = sum(p["pageviews"] for p in points)
    assert total_pv == 1
    zero_days = sum(1 for p in points if p["pageviews"] == 0)
    assert zero_days >= 5


