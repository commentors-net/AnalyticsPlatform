@pytest.mark.asyncio
async def test_askanna_vendored_sdk_pageview_mapping(client: AsyncClient, askanna_setup, db_session):
    """Verify AskAnna pageview wire payload maps client_device, client_browser, and referrer_category."""
    app_id = askanna_setup["app_id"]
    write_key = askanna_setup["write_key"]
    auth_headers = askanna_setup["auth_headers"]

    now = datetime.now(timezone.utc)
    load_id = str(uuid.uuid4())
    event_id = str(uuid.uuid4())

    # Exact payload generated by AskAnna's vendored AnalyticsClient
    payload = {
        "batch": [
            {
                "event_id": event_id,
                "event_type": "pageview",
                "event_name": "pageview",
                "page_path": "/",
                "visitor_id": None,
                "session_id": None,
                "referrer": None,
                "duration_ms": None,
                "metadata": {
                    "source": "public_homepage_notification",
                    "client_device": "desktop",
                    "client_browser": "chrome",
                    "referrer_category": "direct",
                },
                "timestamp": now.isoformat(),
            }
        ]
    }

    resp = await client.post(
        "/v1/events/batch",
        json=payload,
        headers={"X-Write-Key": write_key, "User-Agent": "analytics-python/0.1.0"},
    )
    assert resp.status_code == 202
    data = resp.json()
    assert data["processed_count"] == 1
    assert data["failed_count"] == 0

    # Verify device breakdown mapped client_device -> device_family and client_browser -> browser_family
    dev_resp = await client.get(f"/api/v1/analytics/devices?app_id={app_id}&environment=live", headers=auth_headers)
    assert dev_resp.status_code == 200
    dev_data = dev_resp.json()
    assert any(d["name"] == "desktop" and d["count"] >= 1 for d in dev_data["devices"])
    assert any(b["name"] == "Chrome" and b["count"] >= 1 for b in dev_data["browsers"])

    # Verify recent events source and category mapping
    rec_resp = await client.get(f"/api/v1/analytics/recent?app_id={app_id}&environment=live", headers=auth_headers)
    assert rec_resp.status_code == 200
    events = rec_resp.json()
    assert len(events) >= 1
    e = events[0]
    assert e["source"] == "public_homepage_notification"
    assert e["device_family"] == "desktop"
    assert e["browser_family"] == "Chrome"


@pytest.mark.asyncio
async def test_askanna_timing_engagement_and_duration_metrics(client: AsyncClient, askanna_setup, db_session):
    """Verify timing/homepage_engagement events update duration without inflating pageviews."""
    app_id = askanna_setup["app_id"]
    write_key = askanna_setup["write_key"]
    auth_headers = askanna_setup["auth_headers"]

    now = datetime.now(timezone.utc)
    session_id = f"aa_s_{uuid.uuid4()}"
    visitor_id = f"aa_v_{uuid.uuid4()}"

    # 1. Pageview event
    pv_payload = {
        "batch": [
            {
                "event_id": str(uuid.uuid4()),
                "event_type": "pageview",
                "event_name": "pageview",
                "page_path": "/",
                "visitor_id": visitor_id,
                "session_id": session_id,
                "referrer": None,
                "duration_ms": None,
                "metadata": {
                    "source": "public_homepage_notification",
                    "client_device": "mobile",
                    "client_browser": "safari",
                    "referrer_category": "search",
                },
                "timestamp": now.isoformat(),
            }
        ]
    }
    r1 = await client.post(
        "/v1/events/batch",
        json=pv_payload,
        headers={"X-Write-Key": write_key, "User-Agent": "analytics-python/0.1.0"},
    )
    assert r1.status_code == 202

    # 2. Timing / homepage_engagement event for the same session (15 seconds engagement)
    timing_payload = {
        "batch": [
            {
                "event_id": str(uuid.uuid4()),
                "event_type": "timing",
                "event_name": "homepage_engagement",
                "page_path": "/",
                "visitor_id": visitor_id,
                "session_id": session_id,
                "referrer": None,
                "duration_ms": 15000,
                "metadata": {
                    "source": "public_homepage_notification",
                    "client_device": "mobile",
                    "client_browser": "safari",
                    "referrer_category": "search",
                },
                "timestamp": (now + timedelta(seconds=15)).isoformat(),
            }
        ]
    }
    r2 = await client.post(
        "/v1/events/batch",
        json=timing_payload,
        headers={"X-Write-Key": write_key, "User-Agent": "analytics-python/0.1.0"},
    )
    assert r2.status_code == 202

    # Verify overview metrics: 1 pageview, duration updated to 15s, bounce cleared (>= 10s)
    ov_resp = await client.get(f"/api/v1/analytics/overview?app_id={app_id}&environment=live", headers=auth_headers)
    assert ov_resp.status_code == 200
    ov = ov_resp.json()
    assert ov["pageviews"]["value"] == 1.0
    assert ov["sessions"]["value"] == 1.0
    assert ov["visitors"]["value"] == 1.0
    assert ov["avg_duration_sec"]["value"] == 15.0
    assert ov["bounce_rate"]["value"] == 0.0  # Engaged >= 10s -> non-bounce

    # Verify referrers reporting maps referrer_category "search" -> "Search"
    ref_resp = await client.get(f"/api/v1/analytics/referrers?app_id={app_id}&environment=live", headers=auth_headers)
    assert ref_resp.status_code == 200
    refs = ref_resp.json()
    assert any(r["referrer_category"] == "Search" for r in refs)

    # Verify recent events feed includes both events and reports duration_ms for timing
    rec_resp = await client.get(f"/api/v1/analytics/recent?app_id={app_id}&environment=live", headers=auth_headers)
    assert rec_resp.status_code == 200
    events = rec_resp.json()
    timing_ev = next(e for e in events if e["event_type"] == "timing")
    assert timing_ev["event_name"] == "homepage_engagement"
    assert timing_ev["duration_ms"] == 15000


